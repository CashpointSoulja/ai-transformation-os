import type { TeamId, ThemeId } from './org';

// The workflow catalog is the triage agent's map of how Product & Design works.
// Each request is matched against it. The priors (frequency, pain, complexity)
// apply only when the request itself doesn't say. Explicit evidence in the text
// always wins over a prior.

export interface Workflow {
  id: string;
  name: string;
  /** Gerund phrase used in sentences: "Synthesizing research sessions". */
  phrase: string;
  theme: ThemeId;
  /** Weighted phrases. Multi-word phrases score higher because they're more specific. */
  keywords: Record<string, number>;
  /** Teams that typically do this work, used when the request doesn't size itself. */
  teams: TeamId[];
  /** Share of those teams that do this work regularly (0-1). */
  reach: number;
  /** 1 = yearly/ad hoc … 5 = daily */
  baseFrequency: number;
  /** 1 = minor annoyance … 5 = days lost */
  basePain: number;
  /** 1 = S … 4 = XL before adjustments */
  baseComplexity: number;
  /** Typical hours per occurrence per person, used for the hours-saved estimate. */
  hours: number;
  /** Share of the work an agent can realistically take over (human stays in the loop). */
  automatable: number;
}

