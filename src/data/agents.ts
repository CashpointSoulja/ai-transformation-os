import type { TeamId } from './org';

// Fields follow GitLab's AI Catalog model (item type, semver version, visibility,
// triggers) plus what an AI Transformation Owner is accountable for: an owner,
// KPIs, an eval harness and run health.

export type Health = 'healthy' | 'degraded' | 'failing' | 'paused';
export type EvalStatus = 'passing' | 'failing' | 'stale' | 'none';
export type Autonomy = 'crawl' | 'walk' | 'run';

export interface Kpi {
  name: string;
  target: number;
  current: number;
  unit: string;
  /** 'up' = higher is better */
  better: 'up' | 'down';
}

export interface Agent {
  id: string;
  name: string;
  type: 'agent' | 'flow';
  platform: 'Duo Agent Platform' | 'Relevance.ai' | 'Glean';
  version: string;
  owner: string | null;
  ownerTeam: TeamId;
  /** Why there's no owner, when there isn't one. */
  orphanReason?: string;
  workflow: string;
  skill?: string;
  description: string;
  trigger: string;
  autonomy: Autonomy;
  permission: 'Propose-and-wait' | 'Autonomous' | 'Escalate immediately';
  visibility: 'private' | 'restricted' | 'public';
  status: 'production' | 'pilot' | 'retired';
  kpis: Kpi[];
  eval: { status: EvalStatus; score?: number; cases?: number; daysAgo?: number };
  health: Health;
  healthNote?: string;
  lastRunHoursAgo: number;
  runs7d: number;
  successRate: number;
  /** Sparkline: successful runs per day for the last 14 days. */
  history: number[];
  createdFrom?: string;
}

